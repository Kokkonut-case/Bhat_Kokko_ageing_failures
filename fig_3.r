#illustrate the N to infinity prediction
#we dont use this for now
inf_N_solution <- function(t,phi,k,mu_e,chi,f0){
  
  #composite variables for convenience
  alpha <- phi + k*f0
  beta <- phi + k
  
  numerator <- (alpha*exp(beta*t))-phi*(1-f0)
  denominator <- beta + alpha*(exp(beta*t)-1)
  
  #analytical solution
  f <- numerator/denominator
  
  intr_mort <- f/(1-f) 
  return (mu_e + chi*intr_mort)
}

